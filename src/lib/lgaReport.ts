import { AGE_GROUPS, ageGroup } from "./stats";
import { calculateAge } from "./age";
import type { Cell } from "./csv";
import { fromISO, monthLabel, monthOf } from "./utils";
import { VACCINES } from "./vaccines";
import type { ImmunizationRecord, Patient, Visit } from "../types";
import { SERVICE_LINES, inService } from "./serviceCodes";

export interface AgeSexRow {
  label: string;
  male: number;
  female: number;
}
export interface DxRow {
  code: string;
  label: string;
  male: number;
  female: number;
}
export interface LgaReport {
  month: string;
  newRegistrations: number;
  patientsSeen: number;
  totalVisits: number;
  ageSex: AgeSexRow[];
  diagnoses: DxRow[];
  vaccines: { label: string; doses: number }[];
  maternalChild: { label: string; value: number }[];
}

export function computeLgaReport(
  patients: Patient[],
  visits: Visit[],
  shots: ImmunizationRecord[],
  patientMap: Map<string, Patient>,
  month: string,
): LgaReport {
  const ageSex = new Map<string, { male: number; female: number }>(
    AGE_GROUPS.map((g): [string, { male: number; female: number }] => [
      g,
      { male: 0, female: 0 },
    ]),
  );
  const dx = new Map<string, DxRow>();
  const service = new Map<string, number>(
    SERVICE_LINES.map((l): [string, number] => [l.key, 0]),
  );
  const seen = new Set<string>();
  let totalVisits = 0;

  for (const v of visits) {
    if (v.deletedAt || monthOf(v.visitDate) !== month) continue;
    const p = patientMap.get(v.patientId);
    if (!p) continue;

    const side = p.gender === "FEMALE" ? "female" : "male";
    totalVisits++;
    seen.add(p.id);

    // Age on the day of the visit, not today
    ageSex.get(ageGroup(calculateAge(p.dob, fromISO(v.visitDate))))![side]++;

    const label = v.diagnosisLabel?.trim();
    if (label) {
      const key = v.diagnosisCode ?? label;
      const row = dx.get(key) ?? {
        code: v.diagnosisCode ?? "",
        label,
        male: 0,
        female: 0,
      };
      row[side]++;
      dx.set(key, row);
    }
    for (const l of SERVICE_LINES) {
      if (inService(v.diagnosisCode, l))
        service.set(l.key, (service.get(l.key) ?? 0) + 1);
    }
  }

  const doses = new Map<string, number>();
  for (const r of shots) {
    if (
      r.deletedAt ||
      !patientMap.has(r.patientId) ||
      monthOf(r.dateGiven) !== month
    )
      continue;
    const key = `${r.vaccineName}|${r.doseNumber}`;
    doses.set(key, (doses.get(key) ?? 0) + 1);
  }

  const newRegistrations = patients.filter(
    (p) => monthOf(new Date(p.createdAt).toLocaleDateString("en-CA")) === month,
  ).length;

  return {
    month,
    newRegistrations,
    patientsSeen: seen.size,
    totalVisits,
    ageSex: AGE_GROUPS.map((label) => ({
      label,
      ...(ageSex.get(label) ?? { male: 0, female: 0 }),
    })),
    diagnoses: [...dx.values()]
      .sort((a, b) => b.male + b.female - (a.male + a.female))
      .slice(0, 10),
    vaccines: VACCINES.filter((v) =>
      doses.has(`${v.vaccineName}|${v.doseNumber}`),
    ).map((v) => ({
      label: v.label,
      doses: doses.get(`${v.vaccineName}|${v.doseNumber}`) ?? 0,
    })),
    maternalChild: SERVICE_LINES.map((l) => ({
      label: l.label,
      value: service.get(l.key) ?? 0,
    })),
  };
}

export function reportToRows(
  r: LgaReport,
  facility: { name: string; lga: string; state: string },
): Cell[][] {
  return [
    ["Prima monthly summary"],
    ["Facility", facility.name],
    ["LGA", facility.lga],
    ["State", facility.state],
    ["Month", monthLabel(r.month)],
    [],
    ["Attendance"],
    ["New registrations", r.newRegistrations],
    ["Patients seen", r.patientsSeen],
    ["Total visits", r.totalVisits],
    [],
    ["Visits by age group and sex"],
    ["Age group", "Male", "Female", "Total"],
    ...r.ageSex.map((a) => [a.label, a.male, a.female, a.male + a.female]),
    [],
    ["Top diagnoses (ICD-10)"],
    ["Code", "Diagnosis", "Male", "Female", "Total"],
    ...r.diagnoses.map((d) => [
      d.code,
      d.label,
      d.male,
      d.female,
      d.male + d.female,
    ]),
    [],
    ["Immunization doses given"],
    ["Vaccine", "Doses"],
    ...r.vaccines.map((v) => [v.label, v.doses]),
    [],
    ["Maternal and child (from coded visits)"],
    ["Service", "Visits"],
    ...r.maternalChild.map((m) => [m.label, m.value]),
    [],
    [
      "Generated by Prima from records on this device. Not the official NHMIS form.",
    ],
  ];
}
